"""The apps' offline BS tables hold the months the API computes, for every calculation.

Both apps convert BS ↔ AD on the device from packages/domain/src/calendar/bs-calendar-data/,
generated by scripts.generate_frontend_bs_calendar. If the engine's months move (a rule, an
ayanamsha, a siddhanta fix) and the tables are not regenerated, the device and the server
would disagree on what day it is.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from engine.astronomy.siddhanta import use_ayanamsha, use_siddhanta
from engine.calendar.bikram_sambat import get_bs_month_start_civil
from scripts.generate_frontend_bs_calendar import CALCULATIONS, OUT_DIR

_UNIX_EPOCH_JD = 2440587.5


def _days(iso: str) -> int:
    """Proleptic Gregorian day count since 1970-01-01 of an ISO day, as the apps compute it."""
    sign = -1 if iso.startswith("-") else 1
    y, m, d = (int(x) for x in iso.lstrip("-").split("-"))
    y *= sign
    yy = y - 1 if m <= 2 else y
    era = yy // 400
    yoe = yy - era * 400
    doy = (153 * (m + (-3 if m > 2 else 9)) + 2) // 5 + d - 1
    return era * 146097 + yoe * 365 + yoe // 4 - yoe // 100 + doy - 719468


def _month_starts(table: dict, years: range) -> dict[tuple[int, int], int]:
    packed = table["month_lengths_packed"]
    anchors = table["baisakh_1_ad_anchors"]
    day = None
    out = {}
    for year in range(table["first_year"], years.stop):
        if str(year) in anchors:
            day = _days(anchors[str(year)])
        for month in range(1, 13):
            if year in years:
                out[(year, month)] = day
            day += 29 + int(packed[(year - table["first_year"]) * 12 + month - 1])
    return out


@pytest.mark.parametrize("key, siddhanta_id, ayanamsha", CALCULATIONS)
def test_the_table_is_the_engines_months(key, siddhanta_id, ayanamsha):
    table = json.loads((OUT_DIR / f"{key}.json").read_text(encoding="utf-8"))
    years = range(2070, 2101)
    shipped = _month_starts(table, years)
    with use_siddhanta(siddhanta_id), use_ayanamsha(ayanamsha):
        for (year, month), day in shipped.items():
            engine_day = int(round(get_bs_month_start_civil(year, month).to_jd_ut() - _UNIX_EPOCH_JD))
            assert day == engine_day, f"{key}: BS {year}/{month} — run scripts.generate_frontend_bs_calendar"


def test_every_calculation_ships_a_table():
    assert {p.stem for p in Path(OUT_DIR).glob("*.json")} == {key for key, _, _ in CALCULATIONS}


@pytest.mark.parametrize("file_name, siddhanta_id", [
    ("samvatsara-table.json", "drik"),
    ("samvatsara-table.surya_siddhanta.json", "surya_siddhanta"),
])
def test_the_samvatsara_tables_are_the_engines_names(file_name, siddhanta_id):
    """The apps name each year (60-year cycle) from these tables, one per siddhanta."""
    from engine.calendar.samvatsara import samvatsara_index_for_bs_year

    table = json.loads((OUT_DIR.parent / file_name).read_text(encoding="utf-8"))
    meta = table["_meta"]
    years = [y for y in range(meta["min_year"], meta["max_year"] + 1) if y != 0]
    shipped = dict(zip(years, (ord(c) - 48 for c in table["packed"])))
    with use_siddhanta(siddhanta_id):
        for year in range(1950, 2151):
            assert shipped[year] == samvatsara_index_for_bs_year(year), f"{file_name}: BS {year}"
