/** Native: the same Lucide artwork as web (`AppNavIcon.web.tsx`), drawn with react-native-svg. */
export function AppNavIcon({
  name,
  size,
  color,
}: {
  name: NavIconName;
  size: number;
  color: string;
}) {
  const node = LUCIDE[name];
  if (!node) return null;
  return <LucideNative node={node} size={size} color={color} />;
}
