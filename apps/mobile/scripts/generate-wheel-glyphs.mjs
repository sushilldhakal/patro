/**
 * Generate `lib/wheel-glyph-art.ts` from the rashi / nakshatra SVG assets.
 *
 * react-native-svg's `Svg` always renders a *native view*, never a `<G>`, so a
 * nested `<Svg>` cannot be positioned inside the wheel's SVG tree. The web build
 * sidesteps this by inlining raw markup; on native we need real `<Path>`
 * elements, so the geometry is extracted here and committed as data.
 *
 * Run: node scripts/generate-wheel-glyphs.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const RASHI = [
  "mesha", "vrishabha", "mithuna", "karkat", "simha", "kanya",
  "thula", "vrushika", "dhanu", "makara", "kumbha", "meena",
];

/** अश्विनी → रेवती, matching NAKSHATRA_ICONS order. */
const NAKSHATRA = [
  "ashwini", "bharani", "krittika", "rohini", "mrigashira", "ardra",
  "punarvasu", "pushya", "ashlesha", "magha", "purvaphalguni", "uttaraphalguni",
  "hasta", "chitra", "swathi", "vishakha", "anuradha", "jyeshta",
  "mula", "purvashada", "uttarashada", "shravana", "dhanishta", "shatabisha",
  "purvabhadrapada", "uttarabhadrapada", "revati",
];

/** Decode the XML entities SVG `d` attributes carry (these assets use &#xA;). */
function decodeEntities(v) {
  return v
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
}

function attr(tag, name) {
  const m = tag.match(new RegExp(`${name}\\s*=\\s*"([^"]*)"`));
  return m ? decodeEntities(m[1]) : undefined;
}

function parseGlyph(file) {
  const raw = readFileSync(file, "utf8");

  const svgTag = raw.match(/<svg[^>]*>/)?.[0] ?? "";
  const vb = (attr(svgTag, "viewBox") ?? "0 0 24 24").trim().split(/[\s,]+/).map(Number);

  // Every asset wraps its paths in a single <g> carrying the flip transform and
  // the stroke weight; keep both so the rendered glyph matches the source.
  const gTag = raw.match(/<g[^>]*>/)?.[0] ?? "";
  const transform = attr(gTag, "transform");
  const strokeWidth = attr(gTag, "stroke-width");

  const paths = [...raw.matchAll(/<path[^>]*\/?>/g)].map((m) => {
    const tag = m[0];
    const d = attr(tag, "d");
    if (!d) return null;
    // Newlines inside `d` are legal but noisy; collapse them.
    return {
      d: d.replace(/\s+/g, " ").trim(),
      strokeWidth: attr(tag, "stroke-width"),
    };
  }).filter(Boolean);

  return { vb, transform, strokeWidth, paths };
}

function emit(name, keys, dir) {
  const entries = keys.map((k) => {
    const g = parseGlyph(join(root, "assets", dir, `${k}.svg`));
    const paths = g.paths
      .map((p) => `      { d: ${JSON.stringify(p.d)}${p.strokeWidth ? `, strokeWidth: ${Number(p.strokeWidth)}` : ""} },`)
      .join("\n");
    return [
      `  {`,
      `    vb: [${g.vb.join(", ")}],`,
      g.transform ? `    transform: ${JSON.stringify(g.transform.replace(/\s+/g, " ").trim())},` : "",
      g.strokeWidth ? `    strokeWidth: ${Number(g.strokeWidth)},` : "",
      `    paths: [`,
      paths,
      `    ],`,
      `  },`,
    ].filter(Boolean).join("\n");
  }).join("\n");
  return `export const ${name}: readonly GlyphArt[] = [\n${entries}\n];\n`;
}

const out = `/**
 * Normalised राशि / नक्षत्र glyph geometry for the panchanga wheel.
 *
 * GENERATED by scripts/generate-wheel-glyphs.mjs — do not edit by hand.
 * Re-run it if the SVG assets change.
 */

export interface GlyphPath {
  d: string;
  strokeWidth?: number;
}

export interface GlyphArt {
  /** [minX, minY, width, height] */
  vb: [number, number, number, number];
  /** Group-level transform from the source asset (the y-flip these use). */
  transform?: string;
  /** Group-level stroke width, in the glyph's own viewBox units. */
  strokeWidth?: number;
  paths: GlyphPath[];
}

/** मेष → मीन, matching WHEEL_RASHIS order. */
${emit("RASHI_GLYPHS", RASHI, "rashi")}
/** अश्विनी → रेवती, matching NAKSHATRA_ICONS order. */
${emit("NAKSHATRA_GLYPHS", NAKSHATRA, "nakshatras")}`;

writeFileSync(join(root, "lib", "wheel-glyph-art.ts"), out);
console.log("wrote lib/wheel-glyph-art.ts");
