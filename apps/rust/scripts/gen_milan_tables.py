#!/usr/bin/env python3
"""Write crates/jyotish/src/milan_tables.rs from engine/jyotish/milan.py.

    cd apps/api && ../../.venv/bin/python ../rust/scripts/gen_milan_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))
import engine.jyotish.milan as m  # noqa: E402
from engine.jyotish.interpretation import NAKSHATRA_NE  # noqa: E402


def s(x: str) -> str:
    return json.dumps(x, ensure_ascii=False)


def strs(name, values, doc):
    body = ",\n".join(f"    {s(v)}" for v in values)
    return f"/// {doc}\npub(crate) const {name}: [&str; {len(values)}] = [\n{body},\n];\n"


def ints(name, values, doc, ty="usize"):
    return f"/// {doc}\npub(crate) const {name}: [{ty}; {len(values)}] = [" + ", ".join(str(v) for v in values) + "];\n"


person = {"_rashi": 0, "_nak": 0}
kutas = [m._varna, m._vashya, m._tara, m._yoni, m._maitri, m._gana, m._bhakuta, m._nadi]
rows = [k(person, person) for k in kutas]
out = ["//! Generated by `scripts/gen_milan_tables.py` from `milan.py`; do not edit.\n"]
out.append(strs("KUTA_IDS", [r["id"] for r in rows], "Kuta ids, in payload order."))
out.append(ints("KUTA_MAX", [r["max"] for r in rows], "Points per kuta.", "u32"))
for key in ("areaOfLife", "areaOfLifeNe", "info", "infoNe"):
    out.append(strs("KUTA_" + key.upper(), [r[key] for r in rows], f"`{key}` per kuta."))
out.append(strs("NAKSHATRA_NE", NAKSHATRA_NE, "interpretation's `NAKSHATRA_NE` (its own spellings)."))
out.append(ints("YONI_OF_NAKSHATRA", m.YONI_OF_NAKSHATRA, "`YONI_OF_NAKSHATRA`."))
out.append(strs("YONI_EN", m.YONI_LABELS_EN, "`YONI_LABELS_EN`."))
out.append(strs("YONI_NE", m.YONI_LABELS_NE, "`YONI_LABELS_NE`."))
out.append("/// `_YONI_MATRIX`.\npub(crate) const YONI_MATRIX: [[u32; 14]; 14] = [\n" + ",\n".join("    [" + ", ".join(map(str, r)) + "]" for r in m._YONI_MATRIX) + ",\n];\n")
out.append(ints("GANA_OF_NAKSHATRA", m.GANA_OF_NAKSHATRA, "`GANA_OF_NAKSHATRA`."))
out.append(strs("GANA_EN", m.GANA_LABELS_EN, "`GANA_LABELS_EN`."))
out.append(strs("GANA_NE", m.GANA_LABELS_NE, "`GANA_LABELS_NE`."))
out.append("/// `_GANA_MATRIX`.\npub(crate) const GANA_MATRIX: [[u32; 3]; 3] = [" + ", ".join("[" + ", ".join(map(str, r)) + "]" for r in m._GANA_MATRIX) + "];\n")
out.append(ints("NADI_OF_NAKSHATRA", m.NADI_OF_NAKSHATRA, "`NADI_OF_NAKSHATRA`."))
out.append(strs("NADI_EN", m.NADI_LABELS_EN, "`NADI_LABELS_EN`."))
out.append(strs("NADI_NE", m.NADI_LABELS_NE, "`NADI_LABELS_NE`."))
out.append(ints("VARNA_OF_SIGN", m.VARNA_OF_SIGN, "`VARNA_OF_SIGN` (rank 1–4)."))
out.append(strs("VARNA_EN", [m.VARNA_LABELS_EN[i] for i in range(1, 5)], "`VARNA_LABELS_EN`, rank 1 first."))
out.append(strs("VARNA_NE", [m.VARNA_LABELS_NE[i] for i in range(1, 5)], "`VARNA_LABELS_NE`, rank 1 first."))
out.append(ints("VASHYA_CLASS_OF_SIGN", m.VASHYA_CLASS_OF_SIGN, "`VASHYA_CLASS_OF_SIGN`."))
out.append(strs("VASHYA_EN", m.VASHYA_LABELS_EN, "`VASHYA_LABELS_EN`."))
out.append(strs("VASHYA_NE", m.VASHYA_LABELS_NE, "`VASHYA_LABELS_NE`."))
out.append("/// `VASHYA_CONTROLS`.\npub(crate) const VASHYA_CONTROLS: [&[usize]; 12] = [" + ", ".join("&[" + ", ".join(map(str, sorted(m.VASHYA_CONTROLS[i]))) + "]" for i in range(12)) + "];\n")
dest = Path(__file__).resolve().parents[1] / "crates/jyotish/src/milan_tables.rs"
dest.write_text("\n".join(out))
print("wrote", dest)

# Sentences of compute_ashtakuta, read off results that trigger each branch.
r = m.compute_ashtakuta({"_rashi": 0, "_nak": 0}, {"_rashi": 1, "_nak": 5})  # nadi same? bhakuta diff 1
assert r["nadiDosha"] and r["bhakutaUnfavorable"] and r["totalObtained"] < 18, r["totalObtained"]
extra = ["//"]
lines = {
    "NOTE_NADI": r["notes"][1], "NOTE_NADI_NE": r["notesNe"][1],
    "NOTE_BHAKUTA": r["notes"][2], "NOTE_BHAKUTA_NE": r["notesNe"][2],
    "NOTE_LOW": r["notes"][3], "NOTE_LOW_NE": r["notesNe"][3],
    "NADI_ADVISORY": r["nadiDoshaAdvisory"], "NADI_ADVISORY_NE": r["nadiDoshaAdvisoryNe"],
}
text = dest.read_text()
for k, v in lines.items():
    text += f"\n/// `compute_ashtakuta` sentence.\npub(crate) const {k}: &str = {s(v)};\n"
dest.write_text(text)
