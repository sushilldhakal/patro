#!/usr/bin/env python3
"""Write crates/jyotish/src/rashifal/tables.rs from engine/jyotish/rashifal_engine.py.

    cd apps/api && ../../.venv/bin/python ../rust/scripts/gen_rashifal_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))
import engine.jyotish.rashifal_engine as e  # noqa: E402

G = list(e.GOCHAR_GRAHAS)
P = list(e.PERIODS)
TONES = ["worst", "bad", "neutral", "good", "best"]
GRAHA_VARIANT = {g: "Graha::" + g.capitalize() for g in G}


def s(x: str) -> str:
    return json.dumps(x, ensure_ascii=False)


def f(x: float) -> str:
    r = repr(float(x))
    return r if ("." in r or "e" in r) else r + ".0"


def strs(name: str, values: list[str], doc: str) -> str:
    body = ",\n".join(f"    {s(v)}" for v in values)
    return f"/// {doc}\npub(crate) const {name}: [&str; {len(values)}] = [\n{body},\n];\n"


out = ["//! Generated by `scripts/gen_rashifal_tables.py` from `rashifal_engine.py`; do not edit.\n",
       "use crate::Graha;\n"]

rows = ",\n".join("    &[" + ", ".join(str(h) for h in sorted(e.GOCHAR_BENEFIC_HOUSES[g])) + "]" for g in G)
out.append(f"/// `GOCHAR_BENEFIC_HOUSES`, by graha.\npub(crate) const GOCHAR_BENEFIC_HOUSES: [&[usize]; 9] = [\n{rows},\n];\n")

rows = ",\n".join("    [" + ", ".join(str(e.VEDHA[g].get(h, 0)) for h in range(13)) + "]" for g in G)
out.append(f"/// `VEDHA[graha][house]`: the obstructing house, 0 for none.\npub(crate) const VEDHA: [[usize; 13]; 9] = [\n{rows},\n];\n")

rows = ",\n".join("    [" + ", ".join(f(e.GRAHA_PERIOD_WEIGHT[p][g]) for g in G) + "]" for p in P)
out.append(f"/// `GRAHA_PERIOD_WEIGHT[period][graha]`.\npub(crate) const GRAHA_PERIOD_WEIGHT: [[f64; 9]; 4] = [\n{rows},\n];\n")

L = list(e.LAYER_KEYS)
assert all(list(e.LAYER_WEIGHTS[p]) == L for p in P)
rows = ",\n".join("    [" + ", ".join(f(e.LAYER_WEIGHTS[p][k]) for k in L) + "]" for p in P)
out.append(f"/// `LAYER_WEIGHTS[period][layer]`, layers in `LAYER_KEYS` order.\npub(crate) const LAYER_WEIGHTS: [[f64; 8]; 4] = [\n{rows},\n];\n")
out.append(strs("LAYER_KEYS", L, "`LAYER_KEYS`."))
out.append(strs("LAYER_LABEL_NE", [e.LAYER_LABEL_NE[k] for k in L], "`LAYER_LABEL_NE`, by layer."))
out.append(strs("LAYER_LABEL_EN", [e.LAYER_LABEL_EN[k] for k in L], "`LAYER_LABEL_EN`, by layer."))

out.append(f"/// `CYCLE_GRAHA`, by period.\npub(crate) const CYCLE_GRAHA: [Graha; 4] = [" + ", ".join(GRAHA_VARIANT[e.CYCLE_GRAHA[p]] for p in P) + "];\n")
out.append("/// `HOUSE_STANDING[house]` (index 0 unused).\npub(crate) const HOUSE_STANDING: [f64; 13] = [0.0, " + ", ".join(f(e.HOUSE_STANDING[h]) for h in range(1, 13)) + "];\n")

M = ["swarna", "rajata", "tamra", "loha"]
out.append("/// `_MOORTI_BY_HOUSE[house]` as an index into the moorti tables (index 0 unused).\npub(crate) const MOORTI_BY_HOUSE: [usize; 13] = [0, " + ", ".join(str(M.index(e._MOORTI_BY_HOUSE[h])) for h in range(1, 13)) + "];\n")
out.append(strs("MOORTI_KEYS", M, "Moorti keys."))
out.append(strs("MOORTI_NE", [e.MOORTI_NE[m] for m in M], "`MOORTI_NE`, by moorti."))
out.append(strs("MOORTI_EN", [e.MOORTI_EN[m] for m in M], "`MOORTI_EN`, by moorti."))
out.append("/// `_MOORTI_SCORE`, by moorti.\npub(crate) const MOORTI_SCORE: [f64; 4] = [" + ", ".join(f(e._MOORTI_SCORE[m]) for m in M) + "];\n")

out.append("/// `LORD_NUMBER`, by graha.\npub(crate) const LORD_NUMBER: [u32; 9] = [" + ", ".join(str(e.LORD_NUMBER[g]) for g in G) + "];\n")
for name in ("LORD_COLOR_NE", "LORD_COLOR_EN", "LORD_DISHA_NE", "LORD_DISHA_EN", "REMEDY_NE", "REMEDY_EN"):
    out.append(strs(name, [getattr(e, name)[g] for g in G], f"`{name}`, by graha."))

D = list(e.DOMAIN_KEYS)
out.append(strs("DOMAIN_KEYS", D, "`DOMAIN_KEYS`."))
out.append(strs("DOMAIN_NE", [e.DOMAIN_NE[d] for d in D], "`DOMAIN_NE`, by domain."))
out.append(strs("DOMAIN_EN", [e.DOMAIN_EN[d] for d in D], "`DOMAIN_EN`, by domain."))
rows = ",\n".join("    &[" + ", ".join(f"({h}, {f(w)})" for h, w in e.DOMAIN_HOUSES[d].items()) + "]" for d in D)
out.append(f"/// `DOMAIN_HOUSES` in dict order: (house, weight).\npub(crate) const DOMAIN_HOUSES: [&[(usize, f64)]; 6] = [\n{rows},\n];\n")
rows = ",\n".join("    &[" + ", ".join(GRAHA_VARIANT[k] for k in e.DOMAIN_KARAKA[d]) + "]" for d in D)
out.append(f"/// `DOMAIN_KARAKA`, by domain.\npub(crate) const DOMAIN_KARAKA: [&[Graha]; 6] = [\n{rows},\n];\n")

out.append(strs("HOUSE_THEME_NE", [""] + [e.HOUSE_THEME_NE[h] for h in range(1, 13)], "`HOUSE_THEME_NE[house]` (index 0 unused)."))
out.append(strs("HOUSE_THEME_EN", [""] + [e.HOUSE_THEME_EN[h] for h in range(1, 13)], "`HOUSE_THEME_EN[house]` (index 0 unused)."))
out.append(strs("PERIOD_NE", [e.PERIOD_NE[p] for p in P], "`PERIOD_NE`, by period."))
out.append(strs("PERIOD_EN", [e.PERIOD_EN[p] for p in P], "`PERIOD_EN`, by period."))
out.append(strs("TONE_KEYS", TONES, "Tones, worst first (the `TONE_RANK` order)."))
for name in ("_TONE_OPENER_NE", "_TONE_OPENER_EN", "_TONE_CLOSER_NE", "_TONE_CLOSER_EN"):
    out.append(strs(name.lstrip("_"), [getattr(e, name)[t] for t in TONES], f"`{name}`, by tone."))

DG = ["exalted", "moolatrikona", "own", "friend", "neutral", "enemy", "debilitated"]
out.append(strs("DIGNITY_KEYS", DG, "Dignity keys."))
out.append(strs("DIGNITY_NE", [e.DIGNITY_NE[k] for k in DG], "`DIGNITY_NE`, by dignity."))
out.append(strs("DIGNITY_EN", [e.DIGNITY_EN[k] for k in DG], "`DIGNITY_EN`, by dignity."))
R = ["own", "friend", "neutral", "enemy"]
out.append(strs("RELATION_NE", [e._RELATION_NE[k] for k in R], "`_RELATION_NE`, by relation."))
out.append(strs("RELATION_EN", [e._RELATION_EN[k] for k in R], "`_RELATION_EN`, by relation."))
rows = ",\n".join(f"    ({fl}, {s(k)}, {s(ne)}, {s(en)})" for fl, k, ne, en in e.GRADE_FLOOR)
out.append(f"/// `GRADE_FLOOR`: (percent floor, key, ne, en).\npub(crate) const GRADE_FLOOR: [(i64, &str, &str, &str); 4] = [\n{rows},\n];\n")

dest = Path(__file__).resolve().parents[1] / "crates/jyotish/src/rashifal/tables.rs"
dest.write_text("\n".join(out))
print("wrote", dest)

# ── personal (engine/jyotish/rashifal_personal.py) ─────────────────────────
import engine.jyotish.rashifal_personal as pp  # noqa: E402

assert pp.HOUSE_THEME_NE == e.HOUSE_THEME_NE and pp.HOUSE_THEME_EN == e.HOUSE_THEME_EN
assert pp.PERIOD_NE == e.PERIOD_NE and pp.PERIOD_EN == e.PERIOD_EN
PL = list(pp.LAYER_KEYS)
assert all(list(pp.PERSONAL_LAYER_WEIGHTS[p]) == ["gochar", "chandrabala", "moorti", "ashtakavarga", "rashi_lord", "dasha", "cycle", "vaara_hora"] for p in P)
po = ["//! Generated by `scripts/gen_rashifal_tables.py` from `rashifal_personal.py`; do not edit.\n"]
rows = ",\n".join("    [" + ", ".join(f(pp.PERSONAL_LAYER_WEIGHTS[p][k]) for k in PL) + "]" for p in P)
po.append(f"/// `PERSONAL_LAYER_WEIGHTS[period][layer]`, layers in the personal `LAYER_KEYS` order.\npub(crate) const PERSONAL_LAYER_WEIGHTS: [[f64; 8]; 4] = [\n{rows},\n];\n")
po.append(strs("PERSONAL_LAYER_KEYS", PL, "The personal `LAYER_KEYS`."))
po.append(strs("PERSONAL_LAYER_LABEL_NE", [pp.LAYER_LABEL_NE.get(k, k) for k in PL], "`LAYER_LABEL_NE` with `dasha`, by personal layer."))
po.append(strs("PERSONAL_LAYER_LABEL_EN", [pp.LAYER_LABEL_EN.get(k, k) for k in PL], "`LAYER_LABEL_EN` with `dasha`, by personal layer."))
for name in ("_TONE_OPENER_NE", "_TONE_OPENER_EN", "_TONE_CLOSER_NE", "_TONE_CLOSER_EN"):
    po.append(strs("PERSONAL_" + name.lstrip("_"), [getattr(pp, name)[t] for t in TONES], f"Personal `{name}`, by tone."))
CK = ["lagna", "moon", "sun"]
assert list(pp.NATAL_CHAKRA_WEIGHTS) == CK
po.append("/// `NATAL_CHAKRA_WEIGHTS` (lagna, moon, sun).\npub(crate) const NATAL_CHAKRA_WEIGHTS: [f64; 3] = [" + ", ".join(f(pp.NATAL_CHAKRA_WEIGHTS[k]) for k in CK) + "];\n")
for name in ("CHAKRA_NE", "CHAKRA_EN", "CHAKRA_GLOSS_NE", "CHAKRA_GLOSS_EN"):
    po.append(strs(name, [getattr(pp, name)[k] for k in CK], f"`{name}` (lagna, moon, sun)."))
dest = Path(__file__).resolve().parents[1] / "crates/jyotish/src/rashifal/personal_tables.rs"
dest.write_text("\n".join(po))
print("wrote", dest)
