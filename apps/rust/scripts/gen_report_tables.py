#!/usr/bin/env python3
"""Write crates/jyotish/src/report_tables.rs from engine/jyotish/interpretation.py.

The kundali report's prose tables and its Nepali localization pairs (the
longest-first phrase replacements and the word-boundary theme map), exactly as
Python builds and orders them.

    cd apps/api && ../../.venv/bin/python ../rust/scripts/gen_report_tables.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))
import engine.jyotish.interpretation as it  # noqa: E402
from engine.calendar.constants import BS_MONTH_NAMES_NEPALI  # noqa: E402

KEYS = it.PLANET_KEYS
DIGNITIES = ["exalted", "debilitated", "moolatrikona", "own", "friend", "enemy", "neutral"]


def s(x: str) -> str:
    return json.dumps(x, ensure_ascii=False)


def strs(name: str, values, doc: str) -> str:
    body = "".join(f"    {s(v)},\n" for v in values)
    return f"/// {doc}\npub(crate) const {name}: [&str; {len(values)}] = [\n{body}];\n"


def pairs(name: str, values, doc: str) -> str:
    body = "".join(f"    ({s(a)}, {s(b)}),\n" for a, b in values)
    return f"/// {doc}\npub(crate) const {name}: [(&str, &str); {len(values)}] = [\n{body}];\n"


assert [it.PLANET_EN[k] for k in KEYS] == ["Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn", "Rahu", "Ketu"]
out = ["//! Generated by `scripts/gen_report_tables.py` from `interpretation.py`; do not edit.\n"]
out.append(strs("PLANET_NE", [it.PLANET_NE[k] for k in KEYS], "`PLANET_NE`, in graha order."))
out.append(strs("RASHI_EN", it.RASHI_EN, "`RASHI_EN`."))
out.append(strs("RASHI_NE", it.RASHI_NE, "`RASHI_NE`."))
out.append(strs("SIGN_TRAIT_EN", it.SIGN_TRAIT_EN, "`SIGN_TRAIT_EN`."))
out.append(strs("SIGN_TRAIT_NE", it.SIGN_TRAIT_NE, "`SIGN_TRAIT_NE`."))
out.append(strs("NAKSHATRA_EN", it.NAKSHATRA_EN, "`NAKSHATRA_EN`."))
out.append(strs("NAKSHATRA_NE", it.NAKSHATRA_NE, "`NAKSHATRA_NE`."))
out.append(strs("HOUSE_THEME", [""] + [it.HOUSE_THEME[h] for h in range(1, 13)], "`HOUSE_THEME`, by house (index 0 unused)."))
out.append(strs("HOUSE_THEME_NE", [""] + [it.HOUSE_THEME_NE[h] for h in range(1, 13)], "`HOUSE_THEME_NE`, by house."))
for name in ("KARAKA", "KARAKA_NE", "DASHA_THEME", "DASHA_THEME_NE", "PLAIN_THEME_EN", "PLAIN_THEME_NE"):
    table = getattr(it, name)
    out.append(strs(name, [table[k] for k in KEYS], f"`{name}`, in graha order."))
out.append(strs("DIGNITY_PHRASE", [it.DIGNITY_PHRASE[d] for d in DIGNITIES],
                "`DIGNITY_PHRASE`: exalted, debilitated, moolatrikona, own, friend, enemy, neutral."))
out.append(strs("DIGNITY_PHRASE_NE", [it.DIGNITY_PHRASE_NE[d] for d in DIGNITIES], "`DIGNITY_PHRASE_NE`, same order."))
out.append(strs("BS_MONTH_NE", BS_MONTH_NAMES_NEPALI, "`BS_MONTH_NAMES_NEPALI`."))
out.append(pairs("NE_REPLACEMENTS", it._build_ne_replacements(), "`_build_ne_replacements()`, longest first."))
out.append(pairs("NE_WORD_MAP", it._ne_word_map(), "`_ne_word_map()`, longest first."))
out.append(pairs("EN_MONTH_NE", list(it._EN_MONTH_NE.items()), "`_EN_MONTH_NE`."))
dest = Path(__file__).resolve().parents[1] / "crates/jyotish/src/report_tables.rs"
dest.write_text("\n".join(out))
print("wrote", dest)
