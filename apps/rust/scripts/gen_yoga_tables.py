#!/usr/bin/env python3
"""Write crates/jyotish/src/yoga_tables.rs from engine/jyotish/interpretation.py
and engine/jyotish/kundali_detail.py.

Every catalog row's name, polarity and texts (English and Nepali) depend only on
its key, except the `raja_<kendra lord>_<trikona lord>` rows, so one catalog run
gives the whole static table; the Rust catalog supplies only `present`.

    cd apps/api && ../../.venv/bin/python ../rust/scripts/gen_yoga_tables.py
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))
import engine.jyotish.interpretation as it  # noqa: E402
import engine.jyotish.kundali_detail as kd  # noqa: E402
sys.path.insert(0, str(Path(__file__).resolve().parent))
from rust_divergences import apply as _apply_divergences  # noqa: E402

_apply_divergences()


def s(x: str) -> str:
    return json.dumps(x, ensure_ascii=False)


planets = {k: {"longitude": (i * 37.3) % 360, "is_retrograde": False} for i, k in enumerate(it.PLANET_KEYS)}
chart = it.build_chart(planets, {"longitude": 12.0}, {"planets": []}, {"sequence": []},
                       datetime(2000, 1, 1, tzinfo=timezone.utc), is_day=True)
PLANETS = set(it.PLANET_KEYS)


def is_raja_pair(key: str) -> bool:
    parts = key.split("_")
    return len(parts) == 3 and parts[0] == "raja" and parts[1] in PLANETS and parts[2] in PLANETS


rows = [y for y in it.full_yoga_catalog(chart) if not is_raja_pair(y["key"])]
keys = [y["key"] for y in rows]
assert len(keys) == len(set(keys)), "duplicate yoga keys"

out = ["//! Generated by `scripts/gen_yoga_tables.py` from `interpretation.py` and\n"
       "//! `kundali_detail.py`; do not edit.\n"]
out.append("/// A catalog row's fixed text: name, Nepali name, polarity, English and Nepali text.\n"
           "pub(crate) type YogaText = (&'static str, &'static str, &'static str, &'static str, &'static str);\n")
out.append("/// The fixed text of every catalog row but `raja_<lord>_<lord>`, by key.\n"
           "#[expect(clippy::too_many_lines, reason = \"a generated table\")]\n"
           "pub(crate) fn yoga_text(key: &str) -> Option<YogaText> {\n    Some(match key {")
for y in rows:
    out.append(f"        {s(y['key'])} => ({s(y['name'])}, {s(kd._yoga_name_ne(y['key'], y['name']))}, "
               f"{s(y['polarity'])}, {s(y['text'])}, {s(kd._yoga_desc_ne(y))}),")
out.append("        _ => return None,\n    })\n}\n")
out.append("/// Catalog keys in Python's order, the `raja_<lord>_<lord>` rows left out.\n#[cfg(test)]\n"
           f"pub(crate) const STATIC_ORDER: [&str; {len(keys)}] = [\n" + "".join(f"    {s(k)},\n" for k in keys) + "];\n")

assert not any(is_raja_pair(k) for k in (*kd.YOGA_NAME_NE, *kd.YOGA_DESC_NE)), "raja pair overrides"

dest = Path(__file__).resolve().parents[1] / "crates/jyotish/src/yoga_tables.rs"
dest.write_text("\n".join(out))
print("wrote", dest, len(keys), "rows")
