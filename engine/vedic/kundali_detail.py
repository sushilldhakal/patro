def _parse_iso(value: str) -> datetime:
    dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt


def subdivide_yogini_period(lord: str, start: datetime, end: datetime) -> list[dict[str, Any]]:
    """Yogini antardasha children proportional to the 36-year yogini cycle."""
    if start.tzinfo is None:
        start = start.replace(tzinfo=timezone.utc)
    if end.tzinfo is None:
        end = end.replace(tzinfo=timezone.utc)
    total = end - start
    start_idx = YOGINI_SEQUENCE.index(lord)
    cursor = start
    children: list[dict[str, Any]] = []
    for step in range(len(YOGINI_SEQUENCE)):
        sub_lord = YOGINI_SEQUENCE[(start_idx + step) % len(YOGINI_SEQUENCE)]
        frac = YOGINI_YEARS[sub_lord] / float(sum(YOGINI_YEARS.values()))
        sub_end = end if step == len(YOGINI_SEQUENCE) - 1 else cursor + total * frac
        children.append({
            "lord": sub_lord,
            "lord_ne": YOGINI_LORD_NE[sub_lord],
            "start": cursor.isoformat(),
            "end": sub_end.isoformat(),
        })
        cursor = sub_end
    return children


def subdivide_dasha_period(lord: str, start: datetime, end: datetime) -> list[dict[str, Any]]:
    """Antardasha children proportional to Vimshottari within [start, end)."""
    if start.tzinfo is None:
        start = start.replace(tzinfo=timezone.utc)
    if end.tzinfo is None:
        end = end.replace(tzinfo=timezone.utc)
    total = end - start
    start_idx = DASHA_ORDER.index(lord)
    cursor = start
    children: list[dict[str, Any]] = []
    for step in range(9):
        sub_lord = DASHA_ORDER[(start_idx + step) % 9]
        frac = DASHA_YEARS[sub_lord] / 120.0
        sub_end = end if step == 8 else cursor + total * frac
        children.append({
            "lord": sub_lord,
            "lord_ne": DASHA_LORD_NE[sub_lord],
            "start": cursor.isoformat(),
            "end": sub_end.isoformat(),
        })
        cursor = sub_end
    return children


def _tree_node(
    lord: str,
    start: datetime,
    end: datetime,
    depth: int,
    *,
    subdivide_fn=subdivide_dasha_period,
    lord_ne_map: dict[str, str] | None = None,
) -> dict[str, Any]:
    ne_map = lord_ne_map or DASHA_LORD_NE
    node = {
        "lord": lord,
        "lord_ne": ne_map.get(lord, lord),
        "start": start.isoformat(),
        "end": end.isoformat(),
    }
    if depth > 1:
        node["children"] = [
            _tree_node(
                child["lord"],
                _parse_iso(child["start"]),
                _parse_iso(child["end"]),
                depth - 1,
                subdivide_fn=subdivide_fn,
                lord_ne_map=lord_ne_map,
            )
            for child in subdivide_fn(lord, start, end)
        ]
    return node


def _cycles_for_horizon(birth_instant: datetime, cycle_years: float, horizon_years: float = 10.0) -> int:
    """How many dasha cycles to generate so the sequence still covers 'now'.

    A single cycle (e.g. Yogini's 36 years, Tribhagi's 40) only spans that
    many years from birth — for anyone older than that, "now" falls outside
    every generated period and no mahadasha is ever found "running". Compute
    enough cycles to reach the current real-world moment plus a margin.
    """
    now = datetime.now(timezone.utc)
    if birth_instant.tzinfo is None:
        birth_instant = birth_instant.replace(tzinfo=timezone.utc)
    elapsed_years = max(0.0, (now - birth_instant).total_seconds() / (365.2425 * 86400))
    needed_years = elapsed_years + horizon_years
    return max(1, math.ceil(needed_years / cycle_years))


def _dasha_window(sequence: list[dict[str, Any]], maha_count: int) -> list[dict[str, Any]]:
    """Pick which `maha_count` consecutive mahadashas to surface.

    Rather than always the first N from birth (which silently excludes
    "now" once someone is older than N mahadashas' combined span), center
    the window on whichever period is currently running so the tree the
    frontend receives always contains the "running" one.
    """
    now = datetime.now(timezone.utc)
    current_idx = next(
        (i for i, p in enumerate(sequence) if _parse_iso(p["start"]) <= now < _parse_iso(p["end"])),
        None,
    )
    if current_idx is None:
        return sequence[:maha_count]
    start_idx = max(0, min(current_idx - 1, len(sequence) - maha_count))
    return sequence[start_idx : start_idx + maha_count]


def _build_dasha_tree(
    dasha: dict[str, Any],
    *,
    tree_depth: int = 3,
    maha_count: int = 3,
    subdivide_fn=subdivide_dasha_period,
    lord_ne_map: dict[str, str] | None = None,
) -> dict[str, Any]:
    tree: list[dict[str, Any]] = []
    for period in _dasha_window(dasha["sequence"], maha_count):
        start = _parse_iso(period["start"])
        end = _parse_iso(period["end"])
        tree.append(
            _tree_node(
                period["lord"],
                start,
                end,
                tree_depth,
                subdivide_fn=subdivide_fn,
                lord_ne_map=lord_ne_map,
            )
        )
    return {**dasha, "tree": tree, "tree_depth": tree_depth}


def _build_varga_charts(points: dict[str, dict[str, Any]]) -> dict[str, Any]:
    owned = _owned_rashis()
    entries: dict[str, list[dict[str, Any]]] = {}
    for division in VARGA_DIVISIONS:
        div_key = str(division)
        rows: list[dict[str, Any]] = []
        for key, info in points.items():
            lon = float(info["longitude"])
            varga_rashi = varga_rashi_from_longitude(division, lon)
            nak_idx, pada = nakshatra_of(lon)
            owner_key = SIGN_LORD[varga_rashi - 1]
            planet_key = None if key == "lagna" else key
            rows.append({
                "key": key,
                "vargaRashi": varga_rashi,
                "dms": _dms_parts(lon),
                "nakshatraIndex": nak_idx,
                "pada": pada,
                "nakshatraLord": NAK_LORD[nak_idx],
                "subLord": _kp_sub_lord(lon),
                "ownerKey": owner_key,
                "relation": _relation(planet_key, owner_key) if planet_key else None,
                "dignity": _dignity_api(planet_key, lon, varga_rashi, division) if planet_key else None,
                "retrograde": bool(info.get("retrograde")) if key != "lagna" else False,
            })
        entries[div_key] = rows
    return {
        "divisions": list(VARGA_DIVISIONS),
        "points": {
            k: {
                "longitude": v["longitude"],
                **({"retrograde": v["retrograde"]} if v.get("retrograde") else {}),
            }
            for k, v in points.items()
        },
        "entries": entries,
        "ownedRashis": owned,
    }


def build_kundali_detail(
    instant_local: datetime,
    location: ObserverLocation,
    ayanamsha: str | None = None,
) -> dict[str, Any]:
    """Assemble the full /kundali/detail JSON payload."""
    ayanamsha_label, mode_id = resolve_ayanamsha_mode(ayanamsha)
    instant_utc = instant_local.astimezone(timezone.utc)

    panchanga = build_panchanga_at_time(instant_local, location, ayanamsa=mode_id)
    snapshot = build_planetary_snapshot(
        instant_utc, lat=location.lat, lon=location.lon, ayanamsa=mode_id,
    )
    planets = snapshot["planets"]
    lagna = snapshot["lagna"]
    lagna_lon = float(lagna["longitude"])
    lagna_rashi = sign_of(lagna_lon) + 1

    shadbala = compute_shadbala(
        instant_utc,
        lat=location.lat,
        lon=location.lon,
        timezone_name=location.timezone,
        ayanamsa=mode_id,
    )

    moon_lon = float(planets["moon"]["longitude"])
    vimshottari_cycle_years = sum(DASHA_YEARS.values())
    tribhagi_cycle_years = vimshottari_cycle_years / 3
    dasha = vimshottari_dasha(
        moon_lon, instant_utc, cycles=_cycles_for_horizon(instant_utc, vimshottari_cycle_years)
    )
    dasha_tree = _build_dasha_tree(dasha, tree_depth=3, maha_count=3)
    tribhagi = tribhagi_dasha(
        moon_lon, instant_utc, cycles=_cycles_for_horizon(instant_utc, tribhagi_cycle_years)
    )
    tribhagi_tree = _build_dasha_tree(tribhagi, tree_depth=3, maha_count=3)
    yogini = yogini_dasha(
        moon_lon, instant_utc, cycles=_cycles_for_horizon(instant_utc, YOGINI_CYCLE_YEARS)
    )
    yogini_tree = _build_dasha_tree(
        yogini,
        tree_depth=2,
        maha_count=3,
        subdivide_fn=subdivide_yogini_period,
        lord_ne_map=YOGINI_LORD_NE,
    )

    is_day: Optional[bool] = None
    try:
        from engine.vedic.at_time import resolve_vedic_day_anchor

        _, sunrise_utc, sunset_utc, _ = resolve_vedic_day_anchor(instant_local, location)
        is_day = sunrise_utc <= instant_utc < sunset_utc
    except Exception:
        pass

    _upagraha_raw = {row["key"]: row for row in (panchanga.get("detail") or {}).get("upagrahas") or []}
    _gulika_lon = _upagraha_raw.get("gulika", {}).get("longitude")
    _mandi_lon = _upagraha_raw.get("mandi", {}).get("longitude")

    chart = build_chart(
        planets, lagna, shadbala, dasha, datetime.now(timezone.utc), is_day=is_day,
        gulika_lon=_gulika_lon, mandi_lon=_mandi_lon,
    )

    points: dict[str, dict[str, Any]] = {"lagna": {"longitude": lagna_lon, "retrograde": False}}
    for key in PLANET_KEYS:
        raw = planets.get(key)
        if not raw:
            continue
        points[key] = {
            "longitude": float(raw["longitude"]),
            "retrograde": bool(raw.get("is_retrograde", raw.get("retrograde", False))),
        }

    varga_charts = _build_varga_charts(points)

    detail = panchanga.get("detail") or {}
    upagrahas = _format_upagrahas(detail.get("upagrahas") or [])

    birth_clock = instant_local.strftime("%H:%M")
    ishta, ahoratri_ishta = _compute_ishta_kalas(instant_local, location, panchanga)
    solar = _solar_corrections_block(panchanga)
    correction_min = _signed_solar_minutes(solar.get("belaantar"))

    moon_nak_idx, moon_pada = nakshatra_of(moon_lon)
    yoga_block = panchanga.get("yoga") or {}
    # The yoga block carries a 1-based "number" (no "index" key), so this
    # must be derived from it — reading a nonexistent "index" key silently
    # defaulted to 0 (Vishkambha) for every single chart.
    yoga_index = int(yoga_block.get("number", 1)) - 1

    sun_lon = float(planets["sun"]["longitude"])

    planet_lons = {
        key: float(planets[key]["longitude"])
        for key in ("sun", "moon", "mars", "mercury", "jupiter", "venus", "saturn")
        if planets.get(key)
    }
    ashtakavarga = compute_ashtakavarga(planet_lons, lagna_lon)
    bhava_bala = compute_bhava_bala(lagna_rashi, planet_lons, shadbala)
    yuddha = compute_yuddha_bala(shadbala.get("planets") or [], planet_lons)

    from engine.vedic.vimshopaka import compute_vimshopaka
    vimshopaka_d1_signs = {p: sign_of(lon) for p, lon in planet_lons.items()}
    vimshopaka = compute_vimshopaka(planet_lons, vimshopaka_d1_signs)

    from engine.vedic.interpretation import combust_orb
    combustion: dict[str, bool | None] = {}
    for key in PLANET_KEYS:
        if key not in COMBUST_ORB:
            combustion[key] = None
        elif key == "moon":
            combustion[key] = _angular_sep(moon_lon, sun_lon) < COMBUST_ORB["moon"]
        else:
            raw = planets.get(key)
            lon = float(raw["longitude"]) if raw else None
            retro = bool(raw.get("is_retrograde", raw.get("retrograde", False))) if raw else False
            orb = combust_orb(key, retro)
            combustion[key] = (
                lon is not None and orb is not None and _angular_sep(lon, sun_lon) < orb
            )

    return {
        "panchanga": panchanga,
        "shadbala": shadbala,
        "dasha": dasha_tree,
        "tribhagiDasha": tribhagi_tree,
        "yoginiDasha": yogini_tree,
        "yuddha": yuddha,
        "bhavaBala": bhava_bala,
        "vimshopaka": vimshopaka,
        "ashtakavarga": ashtakavarga,
        "yogas": _yogas_to_api(full_yoga_catalog(chart)),
        "vargaCharts": varga_charts,
        "upagrahas": upagrahas,
        "avakahada": _build_avakahada(moon_lon, sign_of(moon_lon) + 1, lagna_rashi),
        "birthMeta": {
            "birthClock": birth_clock,
            "isDayBirth": is_day,
            "ishtaKala": ishta,
            "ahoratriIshtaKala": ahoratri_ishta,
            "choghadiyaAtBirth": _choghadiya_at_birth(panchanga, birth_clock),
            "solarCorrectionMinutes": round(correction_min, 4),
            "moonNakshatra": {
                "index": moon_nak_idx,
                "number": moon_nak_idx + 1,
                "pada": moon_pada,
            },
            "yoga": {"index": yoga_index, "number": yoga_index + 1},
        },
        "combustion": combustion,
        "lagnaRashi": lagna_rashi,
        "ayanamsha": ayanamsha_label,
        "location": location.as_dict(),
        "birth_instant": instant_local.isoformat(),
    }
