#!/usr/bin/env node
// Copies the Meteocons the weather page draws into the UI kit as string modules.
// Usage: node packages/ui/scripts/meteocons.mjs <@meteocons/svg dir> <@meteocons/svg-static dir>
// (unpacked npm tarballs of @meteocons/svg and @meteocons/svg-static, "fill" style). MIT, Bas Milius.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [animatedDir, staticDir] = process.argv.slice(2);
if (!animatedDir || !staticDir) throw new Error("usage: meteocons.mjs <svg dir> <svg-static dir>");

export const NAMES = [
  "clear-day", "clear-night", "partly-cloudy-day", "partly-cloudy-night", "overcast-day", "overcast-night",
  "fog-day", "fog-night", "drizzle", "rain", "partly-cloudy-day-rain", "partly-cloudy-night-rain", "snow",
  "thunderstorms-day-rain", "thunderstorms-night-rain",
  "sunrise", "sunset", "humidity", "wind", "raindrop", "raindrops", "thermometer", "umbrella", "sun-hot",
  "moon-new", "moon-waxing-crescent", "moon-first-quarter", "moon-waxing-gibbous", "moon-full",
  "moon-waning-gibbous", "moon-last-quarter", "moon-waning-crescent",
  ...Array.from({ length: 11 }, (_, i) => `uv-index-${i + 1}`),
];

const header = (kind) => `/**
 * Meteocons (${kind}), "fill" style — https://github.com/basmilius/meteocons
 * MIT License, Copyright (c) 2020-present Bas Milius.
 * Generated by packages/ui/scripts/meteocons.mjs; do not edit by hand.
 */
`;

const root = new URL("../src/kit/weather/generated/", import.meta.url).pathname;
for (const [dir, file, kind] of [
  [animatedDir, "meteocons-animated.ts", "animated, for the website"],
  [staticDir, "meteocons-static.ts", "static, for the app: react-native-svg does not play SMIL"],
]) {
  const body = NAMES.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(readFileSync(join(dir, "fill", `${n}.svg`), "utf8").trim())},`).join("\n");
  writeFileSync(join(root, file), `${header(kind)}import type { MeteoconName } from "./meteocon-names";\n\nexport const meteocons: Record<MeteoconName, string> = {\n${body}\n};\n`);
}
writeFileSync(
  join(root, "meteocon-names.ts"),
  `${header("names")}export const METEOCON_NAMES = ${JSON.stringify(NAMES, null, 2)} as const;\n\nexport type MeteoconName = (typeof METEOCON_NAMES)[number];\n`,
);
console.log(`${NAMES.length} icons`);
