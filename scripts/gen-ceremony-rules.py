#!/usr/bin/env python3
"""Generates packages/domain/src/festivals/ceremony-rules.generated.ts from patro/src/sait.rs (the ceremony rule
literals), so the shared engine and the Rust server hold the same rules. Run: python3 scripts/gen-ceremony-rules.py"""
import json, re
src = open("apps/rust/crates/patro/src/sait.rs").read()
consts = {}
for m in re.finditer(r'const ([A-Z_]+): \[[^=]*?\] = \[(.*?)\];', src, re.S):
    items = [x.strip().strip('"') for x in m.group(2).replace("\n", " ").split(",") if x.strip()]
    try: consts[m.group(1)] = [int(x) for x in items]
    except ValueError: consts[m.group(1)] = items
consts["VYATIPATA_YOGA"] = [17]; consts["VAIDHRITI_YOGA"] = [27]
for m in re.finditer(r'const ([A-Z_]+): u32 = (\d+);', src): consts[m.group(1)] = [int(m.group(2))]
body = src[src.index("fn ceremony_rules()"):src.index("fn toggleable_rule_ids")]
def ev(e):
    e = e.strip()
    if e == "BTreeSet::new()": return []
    if e in ("true", "false"): return e == "true"
    if re.fullmatch(r'"[^"]*"', e): return e.strip('"')
    if re.fullmatch(r"-?\d+", e): return int(e)
    if re.fullmatch(r"-?\d+\.\d+", e): return float(e)
    m = re.fullmatch(r"set\(&\[(.*)\]\)", e, re.S)
    if m:
        out = []
        for x in [y.strip() for y in m.group(1).split(",") if y.strip()]:
            if x.startswith('"'): out.append(x.strip('"'))
            elif re.fullmatch(r"\d+", x): out.append(int(x))
            else: out += consts[x]
        return out
    m = re.fullmatch(r"set\(&([A-Z_]+)\)", e)
    if m: return consts[m.group(1)]
    raise ValueError(e)
rules = {}
for m in re.finditer(r'rules\.insert\(\s*"([a-z-]+)",\s*CeremonyRule \{(.*?)\n        \},\n    \);', body, re.S):
    fields = {}
    for fm in re.finditer(r'\n\s+([a-z_]+): (.*?),(?=\n\s+[a-z_]+: |\n$|$)', m.group(2) + "\n", re.S):
        fields[fm.group(1)] = ev(fm.group(2))
    rules[m.group(1)] = fields
camel = lambda k: re.sub(r"_([a-z])", lambda x: x.group(1).upper(), k)
out = {n: {camel(k): v for k, v in f.items()} for n, f in rules.items()}
open("packages/domain/src/festivals/ceremony-rules.generated.ts", "w").write("// Generated by scripts/gen-ceremony-rules.py from the Rust server's ceremony rules: do not edit.\nexport const CEREMONY_RULES = " + json.dumps(out, ensure_ascii=False, indent=1) + " as const;\n")
print(list(out), len(out["vivah"]))
