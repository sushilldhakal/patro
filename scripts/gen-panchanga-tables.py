#!/usr/bin/env python3
"""Generates packages/domain/src/panchanga/engine/tables.generated.ts from the Rust name tables, so the
shared engine and the Rust server read the same words. Run: python3 scripts/gen-panchanga-tables.py"""
import json, re, sys
R = "apps/rust/crates/panchanga/src/"
FILES = [R + "names.rs", R + "daily.rs", R + "text_tables.rs", R + "lunar_month.rs"]
DECL = re.compile(r'(?:pub(?:\(crate\))?\s+)?const\s+([A-Z0-9_]+)\s*:\s*\[[^=]*?\]\s*=\s*\[', re.S)

def parse_value(s, i):
    while s[i] in " \n\t,": i += 1
    c = s[i]
    if c == '"':
        j = i + 1; out = ""
        while s[j] != '"':
            if s[j] == "\\": out += json.loads('"' + s[j:j+2] + '"') if s[j+1] in '"\\nrt' else s[j+1]; j += 2
            else: out += s[j]; j += 1
        return out, j + 1
    if c in "([":
        close = ")" if c == "(" else "]"; i += 1; items = []
        while True:
            while s[i] in " \n\t,": i += 1
            if s[i] == close: return items, i + 1
            v, i = parse_value(s, i); items.append(v)
    m = re.match(r"-?[0-9][0-9_]*(?:\.[0-9_]+)?(?:e-?[0-9]+)?|true|false", s[i:])
    if not m: raise ValueError(s[i:i+40])
    t = m.group(0)
    return (True if t == "true" else False if t == "false" else float(t.replace("_", "")) if "." in t or "e" in t else int(t.replace("_", ""))), i + len(t)

tables = {}
for f in FILES:
    s = open(f).read()
    for m in DECL.finditer(s):
        try:
            v, _ = parse_value(s, m.end() - 1)
        except Exception:
            continue
        if m.group(1) not in tables: tables[m.group(1)] = v
out = ["// Generated by scripts/gen-panchanga-tables.py from the Rust server's name tables: do not edit.\n"]
for k, v in sorted(tables.items()):
    out.append(f"export const {k} = {json.dumps(v, ensure_ascii=False)} as const;\n")
open("packages/domain/src/panchanga/engine/tables.generated.ts", "w").write("".join(out))
print(len(tables), "tables:", " ".join(sorted(tables))[:600])
