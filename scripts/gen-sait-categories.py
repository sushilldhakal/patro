#!/usr/bin/env python3
"""The sait categories (id, Nepali label) for the shared engine, from the server's rules file.

Run from the repo root: python3 scripts/gen-sait-categories.py
"""
import json

rules = json.load(open("apps/rust/rules/sait_dates_v1.json"))
rows = [{"id": k, "label_ne": v.get("label_ne", k)} for k, v in rules["categories"].items()]
out = "// Generated by scripts/gen-sait-categories.py from apps/rust/rules/sait_dates_v1.json; do not edit.\n"
out += "export const SAIT_CATEGORIES = " + json.dumps(rows, ensure_ascii=False, indent=1) + " as const;\n"
open("packages/domain/src/festivals/sait-categories.generated.ts", "w").write(out)

# The name tables sait.rs prints (weekday, tithi, nakshatra, yoga, karana and rashi names), copied from the Rust source.
import re

src = open("apps/rust/crates/patro/src/sait.rs").read()
names = ["WEEKDAY_EN", "VAARA_NAMES_NE", "TITHI_NAMES_EN", "TITHI_NAMES_NE", "NAKSHATRA_NAMES_NE", "YOGA_NAMES_NE", "KARANA_NAMES_NE", "RASHI_NAMES_EN", "RASHI_NAMES_NE"]
lines = ["// Generated by scripts/gen-sait-categories.py from apps/rust/crates/patro/src/sait.rs; do not edit.\n"]
for name in names:
    m = re.search(rf"const {name}: \[&str; \d+\] = \[(.*?)\];", src, flags=re.S)
    items = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
    lines.append(f"export const SAIT_{name} = {json.dumps(items, ensure_ascii=False)} as const;\n")
open("packages/domain/src/festivals/sait-names.generated.ts", "w").write("\n".join(lines))
