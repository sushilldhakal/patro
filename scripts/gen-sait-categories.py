#!/usr/bin/env python3
"""The sait categories (id, Nepali label) for the shared engine, from the server's rules file.

Run from the repo root: python3 scripts/gen-sait-categories.py
"""
import json

rules = json.load(open("apps/api/rules/sait_dates_v1.json"))
rows = [{"id": k, "label_ne": v.get("label_ne", k)} for k, v in rules["categories"].items()]
out = "// Generated by scripts/gen-sait-categories.py from apps/api/rules/sait_dates_v1.json; do not edit.\n"
out += "export const SAIT_CATEGORIES = " + json.dumps(rows, ensure_ascii=False, indent=1) + " as const;\n"
open("packages/domain/src/festivals/sait-categories.generated.ts", "w").write(out)
